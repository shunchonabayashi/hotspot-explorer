source('app/model.R')
d <- district_data('app/data/districts.csv')
stopifnot(nrow(d) == 64, !anyDuplicated(d$id), sum(d$pilot_area) == 5, sum(d$default_district) == 1)
stopifnot(all(d$exposed_population >= 0), all(d$exposed_population <= d$population_2020))
raw <- read.csv('app/data/source_flood_bgd.csv', stringsAsFactors = FALSE)
i <- match(d$id, raw$ADM2CD_c)
stopifnot(!anyNA(i), isTRUE(all.equal(d$exposed_population, raw$pop_flood[i])))
stopifnot(max(abs(d$exposed_share_pct - 100*raw$pop_flood[i]/raw$pop[i])) < 1e-10)
s <- assess(d); sun <- which(s$district == 'Sunamganj')
stopifnot(abs(s$exposed_share_pct[sun] - 85.7726393404495) < 1e-9)
stopifnot(s$rank_high_to_low[sun] == 2, abs(s$percentile[sun] - 100*62/63) < 1e-10)
stopifnot(s$above_cutoff[sun], !assess(d, 99)$above_cutoff[sun])
stopifnot(assess(d, s$percentile[sun])$above_cutoff[sun])
p <- assess(d, 90, 'share', 'pilot')
stopifnot(p$percentile[sun] == 100, p$comparison_n[sun] == 5, sum(is.na(p$percentile)) == 59)
count <- assess(d, 90, 'count', 'country')
stopifnot(count$rank_high_to_low[count$district == 'Sylhet'] == 1, count$rank_high_to_low[sun] == 5)
stopifnot(identical(s$exposed_population, count$exposed_population))
local <- read.csv('app/data/local_map.csv'); country <- read.csv('app/data/country_map.csv')
stopifnot(setequal(local$id, d$id[d$pilot_area == 1]), setequal(country$id, d$id))
stopifnot(setequal(d$district[d$pilot_area == 1], c('Sunamganj','Sylhet','Habiganj','Netrakona','Kishoreganj')))
out <- assessment_export(s, 90, 'share', 'country', d$id[sun], '2026-10-29 00:00 UTC')
stopifnot(nrow(out) == 64, sum(out$selected_district) == 1, all(out$investment_gap == 'Not assessed'))
stopifnot(all(out$future_climate_changes == 'Not assessed'), all(out$response_cost == 'Not assessed'))
cat('64-district source, formula, neighbour, screening and export checks passed.\n')

